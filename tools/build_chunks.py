#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build blended chunk audio from the phoneme WAVs.

A chunk such as /əns/ should not be played as three separate clips.  This
script cuts the lead-in silence from each phoneme, crossfades the pieces and
writes one continuous WAV per multi-phoneme chunk.  The app then plays that
single file when a chunk tile is tapped.
"""
import json, re, struct, wave
from pathlib import Path
import math

APP = Path(__file__).resolve().parent.parent
PHONICS = APP / 'web' / 'assets' / 'phonics'
OUT = APP / 'web' / 'assets' / 'chunks'
DATA = APP / 'web' / 'assets' / 'pep_all.js'
APPJS = APP / 'web' / 'assets' / 'app.js'
SR = 22050

src = APPJS.read_text(encoding='utf-8')
block = re.search(r'const PHONEME_FILES = \{(.*?)\n  \};', src, re.S).group(1)
FILES = dict(re.findall(r"'([^']+)':\s*'([^']+)'", block))
tokens = re.findall(r"'([^']+)'", re.search(r'const IPA_TOKENS = \[(.*?)\];', src, re.S).group(1))
V = 'iɪeæaɑɒɔʊuʌɜə'
RC = {'er','ɪr','ʊr','ər','ɑːr','ɔːr','ɜːr'}

def tokenize(ipa):
    s = re.sub(r'[/\[\]ˈˌ\s\-]', '', ipa or '')
    out=[]; i=0
    while i < len(s):
        for t in tokens:
            if not s.startswith(t,i): continue
            if t in RC and i+len(t)<len(s) and s[i+len(t)] in V: continue
            out.append(t); i+=len(t); break
        else: i+=1
    return out

def read_wav(name):
    with wave.open(str(PHONICS / (name + '.wav')), 'rb') as w:
        data = w.readframes(w.getnframes())
    return list(struct.unpack('<%dh' % (len(data)//2), data))

def trim(samples):
    win = int(SR * 0.005)
    rms=[]
    for i in range(0,len(samples)-win+1,win):
        seg=samples[i:i+win]; rms.append(math.sqrt(sum(x*x for x in seg)/len(seg)))
    if not rms: return samples
    peak=max(rms) or 1.0
    a=0
    while a < len(rms) and rms[a] < peak*0.02: a+=1
    b=len(rms)-1
    while b > a and rms[b] < peak*0.02: b-=1
    start=max(0,a*win-int(SR*0.01)); end=min(len(samples),(b+1)*win+int(SR*0.01))
    return samples[start:end]

def crossfade(a,b,overlap):
    n=min(overlap,len(a),len(b))
    if n<=0: return a+b
    head=a[:-n]; mid=[int(a[-n+i]*(1-i/n)+b[i]*(i/n)) for i in range(n)]
    return head+mid+b[n:]

def normalize(samples,target=0.14,peak_limit=0.85):
    if not samples: return samples
    mean=sum(samples)/len(samples); samples=[x-mean for x in samples]
    peak=max(abs(x) for x in samples) or 1.0
    rms=math.sqrt(sum(x*x for x in samples)/len(samples)) or 1.0
    gain=min(target*32768.0/rms,peak_limit*32768.0/peak)
    gain=max(0.05,min(gain,12.0))
    return [max(-32768,min(32767,int(round(x*gain)))) for x in samples]

def fade(samples,ms=5):
    n=min(int(SR*ms/1000),len(samples)//2)
    for i in range(n):
        g=i/float(n); samples[i]=int(samples[i]*g); samples[-1-i]=int(samples[-1-i]*g)
    return samples

def write(name,samples):
    with wave.open(str(OUT/(name+'.wav')),'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(struct.pack('<%dh'%len(samples),*samples))

def main():
    units=json.loads(DATA.read_text(encoding='utf-8').split('=',1)[1].strip().rstrip(';'))
    keys=set()
    for u in units:
        for w in u['words']:
            for c in w.get('chunks') or []:
                ts=tokenize(c[1])
                if len(ts)>1: keys.add(re.sub(r'[/\[\]ˈˌ\s\-]','',c[1]))
    OUT.mkdir(parents=True,exist_ok=True)
    for f in OUT.glob('*.wav'): f.unlink()
    mapping={}
    for idx, key in enumerate(sorted(keys)):
        ts=tokenize(key)
        parts=[]
        for t in ts:
            f=FILES.get(t)
            if not f or not (PHONICS/(f+'.wav')).exists():
                parts=[]; break
            parts.append(trim(read_wav(f)))
        if not parts: continue
        out=parts[0]
        for p in parts[1:]: out=crossfade(out,p,int(SR*0.018))
        out=[0]*int(SR*0.05)+fade(normalize(out))
        slug=re.sub(r'[^a-z0-9]+','_',key.lower()).strip('_')
        name='chunk_%02d'%idx + ('_'+slug if slug else '')
        write(name,out)
        mapping[key]='assets/chunks/'+name+'.wav'
    (OUT/'.keep').write_text('')
    js='// generated by tools/build_chunks.py\nwindow.CHUNK_AUDIO = '+json.dumps(mapping,ensure_ascii=False,indent=2)+';\n'
    (APP/'web'/'assets'/'chunk_audio.js').write_text(js,encoding='utf-8')
    (OUT/'manifest.json').write_text(json.dumps(mapping,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('chunks:',len(mapping))
    for k,v in sorted(mapping.items())[:20]: print(' ',k,v)

if __name__=='__main__': main()
